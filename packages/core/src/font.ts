const stripAccents = (ch: string) => ch.normalize('NFD').replace(/[̀-ͯ]/g, '');

export const FONTS: Record<string, PixelFont> = {
  normal: { id: 'normal', name: 'Normal 5×7', capHeight: 7, lineHeight: 10, glyphs: STD, fallback: (ch) => stripAccents(ch) },
  tiny: { id: 'tiny', name: 'Mini 3×5', capHeight: 5, lineHeight: 6, glyphs: TINY, fallback: (ch) => stripAccents(ch).toUpperCase() },
};

export type FontId = keyof typeof FONTS;

export interface TextOptions {
  font?: string;
  scale?: number;
  /** Extra pixels between letters (before scaling). Default 1. */
  spacing?: number;
  /** Extra pixels between lines (before scaling). Default 0. */
  lineSpacing?: number;
  align?: 'left' | 'center' | 'right';
}

function glyphFor(font: PixelFont, ch: string): Glyph {
  return font.glyphs[ch] ?? font.glyphs[font.fallback?.(ch) ?? ''] ?? font.glyphs['?'];
}

const glyphWidth = (gl: Glyph) => Math.max(...gl.rows.map((r) => r.length));

export interface TextLayout {
  width: number;
  height: number;
  /** Pixels relative to (0,0) = top-left of the first line's capitals. */
  pixels: [number, number][];
}

/** Lay out text and return its ink pixels (relative coordinates, before alignment offset). */
export function layoutText(text: string, opts: TextOptions = {}): TextLayout {
  const font = FONTS[opts.font ?? 'normal'] ?? FONTS.normal;
  const s = Math.max(1, Math.min(16, Math.floor(opts.scale ?? 1)));
  const spacing = opts.spacing ?? 1;
  const lineH = font.lineHeight + (opts.lineSpacing ?? 0);
  const lines = text.replace(/\r/g, '').split('\n');
  const widths = lines.map((line) => {
    const chars = [...line];
    return chars.reduce((w, ch, i) => w + glyphWidth(glyphFor(font, ch)) + (i < chars.length - 1 ? spacing : 0), 0);
  });
  const maxW = Math.max(0, ...widths);
  const pixels: [number, number][] = [];
  lines.forEach((line, li) => {
    const lw = widths[li];
    let cx = opts.align === 'center' ? Math.floor((maxW - lw) / 2) : opts.align === 'right' ? maxW - lw : 0;
    const cy = li * lineH;
    for (const ch of line) {
      const gl = glyphFor(font, ch);
      const top = gl.top ?? 0;
      gl.rows.forEach((row, ry) => {
        for (let rx = 0; rx < row.length; rx++) {
          if (row[rx] !== '#') continue;
          for (let sy = 0; sy < s; sy++) for (let sx = 0; sx < s; sx++) {
            pixels.push([(cx + rx) * s + sx, (cy + top + ry) * s + sy]);
          }
        }
      });
      cx += glyphWidth(gl) + spacing;
    }
  });
  const height = ((lines.length - 1) * lineH + font.capHeight) * s;
  return { width: maxW * s, height, pixels };
}

export function measureText(text: string, opts: TextOptions = {}) {
  const { width, height } = layoutText(text, opts);
  return { width, height };
}
