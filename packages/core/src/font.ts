/**
 * Bitmap pixel fonts. Glyph rows use "#" for ink. Row 0 is the top of
 * capital letters; rows can go below the baseline (descenders) or above row 0
 * (accents on capitals, via `top` < 0).
 */
export interface Glyph {
  rows: string[];
  /** Row offset of rows[0] relative to the top of capitals. */
  top?: number;
}

export interface PixelFont {
  id: string;
  name: string;
  /** Height of capital letters. */
  capHeight: number;
  /** Distance between baselines of consecutive lines. */
  lineHeight: number;
  glyphs: Record<string, Glyph>;
  /** Map characters without glyph (e.g. lowercase in a caps-only font). */
  fallback?: (ch: string) => string;
}

