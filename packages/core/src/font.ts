/** Overlay `accent` rows on top of a lowercase glyph (rows 0-1 are free). */
function accentLower(base: Glyph, accent: string[]): Glyph {
  const rows = [...base.rows];
  accent.forEach((a, i) => {
    const w = Math.max(rows[i]?.length ?? 0, a.length);
    let out = '';
    for (let k = 0; k < w; k++) out += a[k] === '#' || rows[i]?.[k] === '#' ? '#' : '.';
    rows[i] = out;
  });
  return { rows };
}

/** Put accent rows above a capital letter (top = -2). */
function accentUpper(base: Glyph, accent: string[]): Glyph {
  const pad = accent.length === 1 ? ['.'.repeat(base.rows[0].length)] : [];
  return { rows: [...accent, ...pad, ...base.rows].slice(0), top: -2 };
}

